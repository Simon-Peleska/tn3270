// Generates src/codepages.js from x3270's Common/unicode.c, so the tables cannot drift.
// Usage: node 3270/scripts/extract-codepages.mjs /path/to/suite3270/Common/unicode.c
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(
  process.argv[2] ?? "/tmp/x3270/suite3270-4.5/Common/unicode.c",
  "utf8",
)
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/\s+/g, " ");

/** @param {string} name */
function block(name) {
  const start = source.indexOf(name);
  if (start < 0) throw new Error(`${name} not found`);
  const open = source.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "{") depth++;
    if (source[i] === "}" && --depth === 0) return source.slice(open + 1, i);
  }
  throw new Error(`${name} not closed`);
}

/** @param {string} text */
const numbers = (text) =>
  text
    .split(",")
    .map((n) => n.trim())
    .filter(Boolean)
    .map((n) => Number(n.startsWith("'") ? n.charCodeAt(1) : n));

const entry =
  /\{ ?"([^"]+)" ?, ?\{([^}]*)\} ?, ?"([^"]*)" ?, ?"([^"]*)" ?, ?(true|false) ?, ?"([^"]*)" ?\}/g;
const pages = [];
for (const m of block("static uni_t uni[]").matchAll(entry)) {
  const code = numbers(m[2]);
  if (code.length !== 190) throw new Error(`${m[1]} has ${code.length} codes`);
  if (m[5] === "true") continue;
  pages.push({
    name: m[1],
    code,
    hostCodepage: m[3],
    cgcsgid: m[4],
    kybdtype: m[6],
  });
}

/** @type {Record<string, string>} */
const aliases = {};
for (const m of block("cpalias_t cpaliases[]").matchAll(
  /\{ "([^"]+)", "([^"]+)" \}/g,
))
  aliases[m[1]] = m[2];

const apl2uc = numbers(block("static ucs4_t apl2uc[256]"));
if (apl2uc.length !== 256) throw new Error("table sizes changed");

const hex = (/** @type {number[]} */ list) =>
  list.map((n) => `0x${n.toString(16)}`).join(",");
let out =
  "// Generated by scripts/extract-codepages.mjs from x3270's Common/unicode.c. Do not edit.\n";
out +=
  "// SBCS code pages only; EBCDIC 0x41..0xfe to Unicode, 0 is undefined.\n\n";
out += "export const CODE_PAGES = {\n";
for (const p of pages) {
  out += `  ${JSON.stringify(p.name)}: { hostCodepage: ${JSON.stringify(p.hostCodepage)}, cgcsgid: ${JSON.stringify(p.cgcsgid)}, kybdtype: ${JSON.stringify(p.kybdtype)}, code: [${hex(p.code)}] },\n`;
}
out += "};\n\n";
out += `export const ALIASES = ${JSON.stringify(aliases, null, 2)};\n\n`;
out += `export const APL2UC = [${hex(apl2uc)}];\n`;
writeFileSync(new URL("../src/codepages.js", import.meta.url), out);
console.log(
  `${pages.length} code pages, ${Object.keys(aliases).length} aliases`,
);
